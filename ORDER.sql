CREATE TABLE PURPLE_ORDERS (
  Order_ID INT PRIMARY KEY,
  Customer_ID INT,
  Order_Date DATE,
  Total_Amount DECIMAL(10,2),
  Order_Status VARCHAR2(50)
);

CREATE TABLE PURPLE_ORDER_ITEM (
  Order_Item_ID INT PRIMARY KEY,
  Order_ID INT,
  Product_ID INT,
  Quantity INT,
  Price DECIMAL(10,2),
  FOREIGN KEY (Order_ID) REFERENCES PURPLE_ORDERS(Order_ID)
);

